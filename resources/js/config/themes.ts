// Función para aplicar un tema
export const applyThemeVariables = (theme: Theme) => {
  const themeConfig = themes[theme];
  if (!themeConfig) return;

  Object.entries(themeConfig.variables).forEach(([key, value]) => {
    document.documentElement.style.setProperty(key, value);
  });
};

// Función para resetear a default (opcional)
export const resetThemeVariables = () => {
  // Reset to default theme
  applyThemeVariables('default');
};